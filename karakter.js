// ==================================
// MENAMPILKAN DAFTAR KARAKTER
// ==================================

function loadCharacters() {

    const grid = document.getElementById("characterGrid");

    grid.innerHTML = "";

    characters.forEach(character => {

        const imageContent = character.image
            ? `<img src="${character.image}" alt="${character.name}">`
            : `<div class="card-placeholder">${character.name.charAt(0)}</div>`;

        grid.innerHTML += `
            <div class="character-card"
                onclick="showProfile('${character.id}')">

                <div class="card-image">
                    ${imageContent}
                </div>

                <div class="card-info">
                    <h2>${character.name}</h2>
                    <p>${character.role}</p>

                    <button class="card-button">
                        Lihat Profil
                    </button>
                </div>

            </div>
        `;

    });

}


// ==================================
// MENAMPILKAN PROFIL KARAKTER
// ==================================

function showProfile(id) {

    const character = characters.find(item => item.id === id);

    if (!character) return;

    document.getElementById("characterList").style.display = "none";
    document.getElementById("characterDetail").style.display = "block";

    const imageContent = character.image
        ? `<img src="${character.image}" alt="${character.name}">`
        : `<div class="detail-placeholder">${character.name.charAt(0)}</div>`;

    const dataContent = character.data.map(item => `
        <div class="profile-data">
            <strong>${item[0]}</strong>
            <span>: ${item[1]}</span>
        </div>
    `).join("");

    document.getElementById("detailContent").innerHTML = `

        <div class="detail-box">

            <div class="detail-image">
                ${imageContent}
            </div>

            <div class="detail-info">

                <h2>${character.name}</h2>

                <p class="character-role">
                    ${character.role}
                </p>

                ${dataContent ? `
                    <div class="profile-section">
                        <h3>Identitas</h3>
                        ${dataContent}
                    </div>
                ` : ""}

                <div class="profile-section">
                    <h3>Tentang Karakter</h3>
                    <p>${character.description}</p>
                </div>

                <div class="profile-section">
                    <h3>Latar Belakang</h3>
                    <p>${character.background}</p>
                </div>

            </div>

        </div>

    `;

    window.scrollTo(0, 0);
}


